#!/usr/bin/env node
/**
 * Compile the postMessage v2 and the embedded-consent-field (field-v1, 202)
 * JSON Schemas into freestanding JS validators using Ajv standalone mode.
 * Output lives under `src/generated/<family>/` and is committed-but-derived:
 * regenerate on any schema edit and commit the resulting JS so CI does not
 * need Ajv at test time.
 */
import Ajv from "ajv/dist/2020.js"
import standaloneCode from "ajv/dist/standalone/index.js"
import addFormats from "ajv-formats"
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const FAMILIES = [
  { label: "postMessage v2", schemaDir: join(__dirname, "../schemas/postmessage-v2"), outDir: join(__dirname, "../src/generated/postmessage-v2") },
  { label: "field v1", schemaDir: join(__dirname, "../schemas/field-v1"), outDir: join(__dirname, "../src/generated/field-v1") },
]

const DTS_BODY =
  "// Auto-generated by scripts/compile-schemas.mjs.\n" +
  "// Types the Ajv standalone-compiled validator function so postmessage_v2.ts\n" +
  "// can consume it without `@ts-expect-error` suppressions.\n" +
  "interface ValidatorFn {\n" +
  "  (data: unknown): boolean\n" +
  "  errors?: Array<Record<string, unknown>> | null\n" +
  "}\n" +
  "declare const validate: ValidatorFn\n" +
  "export default validate\n" +
  "export { validate }\n"

function walk(d, all = []) {
  for (const f of readdirSync(d)) {
    const p = join(d, f)
    if (statSync(p).isDirectory()) walk(p, all)
    else if (p.endsWith(".json")) all.push(p)
  }
  return all
}

for (const { label, schemaDir, outDir } of FAMILIES) {
  mkdirSync(outDir, { recursive: true })
  const ajv = new Ajv({ code: { source: true, esm: true }, strict: false, allErrors: true })
  addFormats(ajv)
  const all = walk(schemaDir)
  for (const p of all) ajv.addSchema(JSON.parse(readFileSync(p, "utf-8")))
  let written = 0
  for (const p of all) {
    const schema = JSON.parse(readFileSync(p, "utf-8"))
    const validate = ajv.getSchema(schema.$id)
    if (!validate) throw new Error(`Could not retrieve compiled validator for ${schema.$id}`)
    const moduleCode = standaloneCode(ajv, validate)
    const rel = relative(schemaDir, p).replace(/\.json$/, ".js")
    const outPath = join(outDir, rel)
    mkdirSync(dirname(outPath), { recursive: true })
    writeFileSync(outPath, moduleCode)
    writeFileSync(outPath.replace(/\.js$/, ".d.ts"), DTS_BODY)
    written++
  }
  console.log(`Compiled ${written} ${label} schema(s) (+ .d.ts) to ${relative(process.cwd(), outDir)}`)
}
